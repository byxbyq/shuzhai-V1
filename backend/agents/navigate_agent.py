class NavigateAgent(BaseAgent):
    """处理页面导航意图：open_page"""

    agent_id = "navigate"
    agent_name = "导航Agent"
    intent_keywords = ["open_page"]

    def execute(self, params: dict, context: dict) -> dict:
        page = (params.get("page") or "").strip()
        self.log_event("open_page", {"page": page})

        if not page:
            return {"reply": "你想打开哪个页面？比如：写作、时间线、伏笔管理、写作统计……"}

        canonical = _PAGE_ALIASES.get(page)
        if canonical is None:
            # 模糊匹配：别名包含用户输入，或用户输入包含别名
            for alias, name in _PAGE_ALIASES.items():
                if alias in page or page in alias:
                    canonical = name
                    break

        if canonical is None:
            return {
                "reply": "我不认识「" + page + "」这个页面。可以打开的页面有：\n"
                         + "、".join(_CANONICAL_PAGES),
            }

        return {
            "reply": "好的，正在打开「" + canonical + "」。",
            "action": {"type": "open_page", "page": canonical},
        }
